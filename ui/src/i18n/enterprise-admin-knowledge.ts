export type EnterpriseAdminKnowledgeCopyKey = keyof typeof copy;

export function knowledgeAdminCopy(
  key: EnterpriseAdminKnowledgeCopyKey,
  params?: Record<string, string>,
): string {
  const value = copy[key][i18n.getLocale() === "vi" ? 0 : 1];
  const brandedValue = brandProductCopy(value);
  return params
    ? brandedValue.replace(/\{(\w+)\}/gu, (_, name: string) => params[name] ?? `{${name}}`)
    : brandedValue;
}

